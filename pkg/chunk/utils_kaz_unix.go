package chunk

// Directory fsync used to make staged writeback blocks durable (non-Windows).

import (
	"os"
)

// fsyncDir makes entries created or renamed in dir durable.
func fsyncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	err = d.Sync()
	if cerr := d.Close(); err == nil {
		err = cerr
	}
	return err
}
